import argparse
import pathlib
import shutil


def copyPackage(source: pathlib.Path, destination: pathlib.Path) -> None:
	"""Copy the contents of a package directory.

	Symlinks are dereferenced so that tree artifacts only contain regular files.
	"""

	shutil.copytree(source, destination, symlinks=False, dirs_exist_ok=True)


if __name__ == "__main__":
	parser = argparse.ArgumentParser(description="Copy the packages of a node_modules directory.")
	parser.add_argument(
		"--copy",
		metavar=("SOURCE", "DIRECTORY"),
		nargs=2,
		action="append",
		default=[],
		help="Source and destination directory, can be used multiple times.",
	)
	args = parser.parse_args()

	for source, directory in args.copy:
		copyPackage(
			source=pathlib.Path(source),
			destination=pathlib.Path(directory),
		)
