import argparse
import pathlib
import tarfile


def extractPackage(archive: pathlib.Path, destination: pathlib.Path) -> None:
	"""Extract the contents of a package archive.

	Tree artifacts must not contain symlinks, therefore symlinks are rejected.
	"""

	with tarfile.open(archive, "r") as tar:
		for member in tar.getmembers():
			if member.issym():
				raise Exception(f"Symlink '{member.name}' found in package '{archive}', this is not supported.")

		destination.mkdir(parents=True, exist_ok=True)
		tar.extractall(destination, filter="data")


if __name__ == "__main__":
	parser = argparse.ArgumentParser(description="Extract the packages of a node_modules directory.")
	parser.add_argument(
		"--extract",
		metavar=("ARCHIVE", "DIRECTORY"),
		nargs=2,
		action="append",
		default=[],
		help="Archive and destination directory, can be used multiple times.",
	)
	args = parser.parse_args()

	for archive, directory in args.extract:
		extractPackage(
			archive=pathlib.Path(archive),
			destination=pathlib.Path(directory),
		)
