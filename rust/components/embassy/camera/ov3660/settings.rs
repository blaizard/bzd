//! OV3660 register tables.
//!
//! Derived from Espressif `esp32-camera` (Apache-2.0):
//! `sensors/private_include/ov3660_settings.h` and `driver/sensor.c`. The
//! original tables derive from the OpenMV project (MIT).

/// One sensor register operation.
#[derive(Clone, Copy)]
pub(crate) enum RegOp {
    /// Write `value` to the 16-bit register `addr`.
    Write { addr: u16, value: u8 },
    /// Wait before applying the next operation.
    DelayMs(u16),
}

pub(crate) const fn write(addr: u16, value: u8) -> RegOp {
    RegOp::Write { addr, value }
}

pub(crate) const fn delay(ms: u16) -> RegOp {
    RegOp::DelayMs(ms)
}

/// Aspect-ratio window geometry used by `set_framesize`.
#[derive(Clone, Copy)]
pub(crate) struct RatioSettings {
    pub max_width: u16,
    pub max_height: u16,
    pub start_x: u16,
    pub start_y: u16,
    pub end_x: u16,
    pub end_y: u16,
    pub total_x: u16,
    pub total_y: u16,
}

/// One named frame size, in esp32-camera `framesize_t` order.
#[derive(Clone, Copy)]
pub(crate) struct Resolution {
    pub width: u16,
    pub height: u16,
    /// Index into [`RATIO_TABLE`].
    pub aspect_ratio: usize,
}

